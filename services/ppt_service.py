"""Builds the .pptx file with python-pptx. Theme: navy / blue / white / light grey. Returns the file as bytes."""
from io import BytesIO

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
from pptx.util import Inches, Pt

from utils.helpers import GenerationError

NAVY = RGBColor(0x0B, 0x25, 0x45)
BLUE = RGBColor(0x1E, 0x6F, 0xD9)
LIGHT_BLUE = RGBColor(0xDC, 0xEB, 0xFB)
LIGHT_GREY = RGBColor(0xF3, 0xF5, 0xF8)
MID_GREY = RGBColor(0x5B, 0x67, 0x7A)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
SLIDE_W, SLIDE_H = 13.333, 7.5  # inches (16:9)


def _background(slide, color):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _rect(slide, left, top, width, height, color, shape=MSO_SHAPE.RECTANGLE):
    box = slide.shapes.add_shape(shape, Inches(left), Inches(top), Inches(width), Inches(height))
    box.fill.solid()
    box.fill.fore_color.rgb = color
    box.line.fill.background()
    return box


def _text(slide, left, top, width, height, lines, size, color, bold=False, align=PP_ALIGN.LEFT, space_after=0):
    """Add a textbox; `lines` is a list of strings (one paragraph each)."""
    frame = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height)).text_frame
    frame.word_wrap = True
    for i, line in enumerate(lines):
        para = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        para.alignment = align
        para.space_after = Pt(space_after)
        run = para.add_run()
        run.text = line
        run.font.size, run.font.bold, run.font.color.rgb, run.font.name = Pt(size), bold, color, "Calibri"
    return frame


def _shape_label(shape, text, size, color):
    frame = shape.text_frame
    frame.word_wrap = True
    frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    para = frame.paragraphs[0]
    para.alignment = PP_ALIGN.CENTER
    run = para.add_run()
    run.text = text
    run.font.size, run.font.bold, run.font.color.rgb, run.font.name = Pt(size), True, color, "Calibri"


def _title_slide(prs, paper_title, subtitle_lines):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _background(slide, NAVY)
    _rect(slide, 0, 0, 0.35, SLIDE_H, BLUE)
    _text(slide, 1.0, 2.0, 11.3, 2.2, [paper_title], 40, WHITE, bold=True)
    _rect(slide, 1.05, 4.25, 2.0, 0.06, LIGHT_BLUE)
    _text(slide, 1.0, 4.5, 11.3, 1.5, subtitle_lines[:3] or ["Research Paper Presentation"], 20, LIGHT_BLUE, space_after=4)
    _text(slide, 1.0, 6.7, 8, 0.4, ["Generated by PaperPilot AI"], 12, MID_GREY)


def _content_slide(prs, number, title, bullets, steps):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _background(slide, WHITE)
    _rect(slide, 0, 0, SLIDE_W, 1.2, NAVY)
    _rect(slide, 0, 1.2, SLIDE_W, 0.07, BLUE)
    _text(slide, 0.6, 0.28, 12.1, 0.8, [title], 32, WHITE, bold=True)

    panel_height = 2.9 if steps else 5.2
    _rect(slide, 0.6, 1.6, 12.1, panel_height, LIGHT_GREY, MSO_SHAPE.ROUNDED_RECTANGLE).adjustments[0] = 0.04
    total_chars = sum(len(b) for b in bullets)
    size = 24 if total_chars < 280 else 20 if total_chars < 480 else 17
    if steps:
        size = min(size, 20)
    _text(slide, 0.9, 1.8, 11.5, panel_height - 0.4, ["•  " + b for b in bullets], size, NAVY, space_after=10)

    if steps:
        _diagram(slide, steps)

    _text(slide, 11.6, 6.95, 1.2, 0.4, [str(number)], 12, MID_GREY, align=PP_ALIGN.RIGHT)
    _text(slide, 0.6, 6.95, 6, 0.4, ["PaperPilot AI"], 12, MID_GREY)


def _diagram(slide, steps):
    """Simple left-to-right flow diagram: rounded boxes joined by arrows."""
    n = len(steps)
    gap = 0.55
    box_w = min(2.3, (12.1 - gap * (n - 1)) / n)
    left = (SLIDE_W - (n * box_w + (n - 1) * gap)) / 2
    top = 5.0
    for i, step in enumerate(steps):
        x = left + i * (box_w + gap)
        box = _rect(slide, x, top, box_w, 1.3, BLUE, MSO_SHAPE.ROUNDED_RECTANGLE)
        _shape_label(box, step, 15, WHITE)
        if i < n - 1:
            _rect(slide, x + box_w + 0.08, top + 0.45, gap - 0.16, 0.4, NAVY, MSO_SHAPE.RIGHT_ARROW)


def build_presentation(paper_title: str, slides: list) -> bytes:
    """slides = [{"title", "bullets", "diagram_steps"}, ...]; the first item is shown as the title slide."""
    try:
        prs = Presentation()
        prs.slide_width, prs.slide_height = Inches(SLIDE_W), Inches(SLIDE_H)
        _title_slide(prs, paper_title, slides[0]["bullets"])
        for number, slide in enumerate(slides[1:], start=2):
            _content_slide(prs, number, slide["title"], slide["bullets"], slide.get("diagram_steps") or [])
        buffer = BytesIO()
        prs.save(buffer)
        return buffer.getvalue()
    except Exception as exc:
        raise GenerationError(f"PowerPoint generation failed: {exc}") from exc
